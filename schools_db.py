def search_schools_from_db(school_name: str) -> list:
    """로컬 DB에서 학교 검색"""
    results = []

    for region, schools in SCHOOL_DATABASE.items():
        for school in schools:
            if school_name.lower() in school["name"].lower() or school["name"].lower() in school_name.lower():
                results.append({
                    "ATPT_OFCDC_SC_CODE": school["code"],
                    "ATPT_OFCDC_SC_NM": school["region"],
                    "SD_SCHUL_CODE": "0000000",
                    "SCHUL_NM": school["name"],
                    "SCHUL_KND_SC_NM": "고등학교" if "고" in school["name"] else "중학교" if "중" in school["name"] else "초등학교"
                })

    return results
